"""Generate the Spanish page (es/index.html) from index.html.

The English page is the source of truth. Spanish texts live in the UI_ES object
inside index.html; this script pre-renders them so search engines see real
Spanish content at https://iacleaner.com/es/.

Usage:  python tools/build_es.py
Run it after every change to index.html, then commit both files.
"""
import pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
src = (ROOT / 'index.html').read_text(encoding='utf-8')

# ---- Spanish UI strings from the UI_ES object in index.html ----
block = src[src.index('const UI_ES = {'):]
block = block[:block.index('\n};')]
ui_es = {k: v.replace("\\'", "'") for k, v in re.findall(r"'([\w.]+)':\s*'((?:[^'\\]|\\.)*)'", block)}

out = src
missing = []

def fill(m):
    key = m.group(3)
    if key not in ui_es:
        missing.append(key)
        return m.group(0)
    return m.group(1) + ui_es[key] + m.group(4)

# Elements whose content is translated: <tag ... data-i18n="key" ...>content</tag>
out = re.sub(r'(<(\w+)\b[^>]*\bdata-i18n="([\w.]+)"[^>]*>)(?:.*?)(</\2>)', fill, out, flags=re.S)

# Translated attributes: data-i18n-ph → placeholder, data-i18n-aria → aria-label
def attr(text, marker, name):
    def rep(m):
        tag, key = m.group(0), m.group(1)
        if key not in ui_es:
            missing.append(key)
            return tag
        return re.sub(rf'\b{name}="[^"]*"', f'{name}="{ui_es[key]}"', tag, count=1)
    return re.sub(rf'<[^>]*\bdata-i18n-{marker}="([\w.]+)"[^>]*>', rep, text)

out = attr(out, 'ph', 'placeholder')
out = attr(out, 'aria', 'aria-label')

# ---- Page-level replacements ----
ES_HEAD = '''<!-- SEO:START -->
<title>IA Cleaner — Elimina metadatos de IA de imágenes, PDF y textos (gratis y privado)</title>
<meta name="description" content="Herramienta online gratuita para eliminar metadatos de IA: C2PA / Content Credentials, EXIF, XMP, prompts en PNG, propiedades de documentos y caracteres ocultos de ChatGPT. Funciona 100 % en tu navegador: no se sube nada.">
<link rel="canonical" href="https://iacleaner.com/es/">
<meta property="og:url" content="https://iacleaner.com/es/">
<meta property="og:locale" content="es_ES">
<meta property="og:locale:alternate" content="en_US">
<meta property="og:title" content="IA Cleaner — Elimina los metadatos de IA de tus archivos">
<meta property="og:description" content="Quita C2PA, EXIF, prompts y caracteres ocultos de imágenes, documentos y textos. Gratis y 100 % privado: todo se procesa en tu navegador.">
<script type="application/ld+json">
{"@context":"https://schema.org","@type":"WebApplication","name":"IA Cleaner","url":"https://iacleaner.com/es/","inLanguage":"es",
 "applicationCategory":"UtilitiesApplication","operatingSystem":"Cualquiera (navegador web)","browserRequirements":"Requiere JavaScript",
 "isAccessibleForFree":true,"offers":{"@type":"Offer","price":"0","priceCurrency":"EUR"},"image":"https://iacleaner.com/logo.webp",
 "description":"Herramienta gratuita que elimina los metadatos relacionados con IA y los caracteres invisibles de imágenes, PDF, documentos de Office y textos, directamente en tu navegador.",
 "featureList":["Eliminar C2PA / Content Credentials","Eliminar metadatos EXIF, XMP e IPTC","Quitar prompts de Stable Diffusion y ComfyUI de PNG","Limpiar propiedades de PDF y documentos de Office","Quitar caracteres ocultos y marcas oaicite de ChatGPT","Procesamiento 100 % en el navegador"]}
</script>
<script type="application/ld+json">
{"@context":"https://schema.org","@graph":[
 {"@type":"WebSite","@id":"https://iacleaner.com/#website","name":"IA Cleaner","alternateName":["iacleaner","iacleaner.com","IACleaner"],"url":"https://iacleaner.com/","inLanguage":["en","es"],"publisher":{"@id":"https://iacleaner.com/#organization"}},
 {"@type":"Organization","@id":"https://iacleaner.com/#organization","name":"IA Cleaner","alternateName":"iacleaner","url":"https://iacleaner.com/","logo":{"@type":"ImageObject","url":"https://iacleaner.com/logo.webp"},"sameAs":["https://github.com/geniscid-commits/ai-cleaner"]}
]}
</script>
<!-- SEO:END -->'''

a, b = out.index('<!-- SEO:START -->'), out.index('<!-- SEO:END -->') + len('<!-- SEO:END -->')
out = out[:a] + ES_HEAD + out[b:]
out = out.replace('<html lang="en">', '<html lang="es">', 1)
out = out.replace('<a class="brand" href="/">', '<a class="brand" href="/es/">', 1)
out = out.replace('data-lang="en" aria-current="page">EN</a>', 'data-lang="en">EN</a>', 1)
out = out.replace('data-lang="es">ES</a>', 'data-lang="es" aria-current="page">ES</a>', 1)
out = out.replace('<!DOCTYPE html>', '<!DOCTYPE html>\n<!-- Generated by tools/build_es.py from index.html. Do not edit by hand. -->', 1)

if missing:
    sys.exit('Missing Spanish translations for: ' + ', '.join(sorted(set(missing))))
(ROOT / 'es').mkdir(exist_ok=True)
(ROOT / 'es' / 'index.html').write_text(out, encoding='utf-8')
print('es/index.html written')
